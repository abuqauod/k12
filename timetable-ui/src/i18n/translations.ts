export const TRANSLATIONS: Record<Lang, Record<TranslationKey, string>> = { en, ar }

/** Fills `{name}` placeholders. Shared by the UI and the English wire payload. */
export function interpolate(
  template: string,
  values?: Record<string, string | number>,
): string {
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  )
}

/** English rendering of a solver justification, for the API payload. */
export function englishMessage(
  key: string,
  values?: Record<string, string | number>,
): string {
  const template = en[key as TranslationKey] ?? key
  const withDay =
    values && typeof values.dayToken === 'string'
      ? { ...values, day: en[`day.${values.dayToken}` as TranslationKey] ?? values.dayToken }
      : values
  return interpolate(template, withDay)
}
